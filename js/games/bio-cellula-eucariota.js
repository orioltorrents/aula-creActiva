const bioCellulaEucariotaQuiz = {
    activeQuestions: [],
    currentQuestion: 0,
    score: 0,
    locked: false,
    finished: false,
    filterLabel: 'Barrejat'
};

function shuffleBioCellula(items) {
    const result = [...items];
    for (let i = result.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [result[i], result[j]] = [result[j], result[i]];
    }
    return result;
}

function initBioCellulaEucariotaQuiz() {
    const activity = document.getElementById('bio-activity-cellula-eucariota');
    if (!activity) return;

    bioCellulaEucariotaQuiz.activeQuestions = [];
    bioCellulaEucariotaQuiz.currentQuestion = 0;
    bioCellulaEucariotaQuiz.score = 0;
    bioCellulaEucariotaQuiz.locked = false;
    bioCellulaEucariotaQuiz.finished = false;
    bioCellulaEucariotaQuiz.filterLabel = 'Barrejat';

    activity.classList.remove('hidden');
    document.getElementById('bio-cellula-eucariota-selection').classList.remove('hidden');
    document.getElementById('bio-cellula-eucariota-ui').classList.add('hidden');
    document.getElementById('bio-cellula-eucariota-results').classList.add('hidden');
    renderBioCellulaFilters();
}

function renderBioCellulaFilters() {
    const container = document.getElementById('bio-cellula-eucariota-filters');
    if (!container) return;
    container.innerHTML = '';

    const topics = [...new Set(BIO_CELLULA_EUCARIOTA_QUESTIONS.map(question => question.topic))];
    const levels = [
        ['easy', 'Fàcil', 'quiz-filter-button--easy'],
        ['medium', 'Mitjà', 'quiz-filter-button--medium'],
        ['hard', 'Difícil', 'quiz-filter-button--hard']
    ];

    const topicLabel = document.createElement('p');
    topicLabel.className = 'w-full text-center font-bold text-gray-600';
    topicLabel.textContent = 'Per tema:';
    container.appendChild(topicLabel);

    topics.forEach(topic => {
        container.appendChild(createBioCellulaFilterButton(topic, topic, 'quiz-filter-button--topic'));
    });

    const levelLabel = document.createElement('p');
    levelLabel.className = 'w-full text-center font-bold text-gray-600 mt-4';
    levelLabel.textContent = 'Per nivell:';
    container.appendChild(levelLabel);

    levels.forEach(([value, label, modifier]) => {
        container.appendChild(createBioCellulaFilterButton(label, value, modifier, 'level'));
    });

    container.appendChild(createBioCellulaFilterButton('Barrejat', 'mixed', 'quiz-filter-button--mixed', 'mixed'));
}

function createBioCellulaFilterButton(label, value, modifier, type = 'topic') {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = `btn btn--primary quiz-filter-button ${modifier}`;
    button.textContent = label;
    button.addEventListener('click', () => startBioCellulaQuiz(type, value, label));
    return button;
}

function startBioCellulaQuiz(type, value, label) {
    let pool = [...BIO_CELLULA_EUCARIOTA_QUESTIONS];
    if (type === 'topic') pool = pool.filter(question => question.topic === value);
    if (type === 'level') pool = pool.filter(question => question.level === value);
    if (pool.length === 0) return;

    bioCellulaEucariotaQuiz.activeQuestions = shuffleBioCellula(pool).slice(0, 10).map(question => ({
        ...question,
        alternatives: shuffleBioCellula(question.alternatives)
    }));
    bioCellulaEucariotaQuiz.currentQuestion = 0;
    bioCellulaEucariotaQuiz.score = 0;
    bioCellulaEucariotaQuiz.locked = false;
    bioCellulaEucariotaQuiz.finished = false;
    bioCellulaEucariotaQuiz.filterLabel = label;

    document.getElementById('bio-cellula-eucariota-selection').classList.add('hidden');
    document.getElementById('bio-cellula-eucariota-ui').classList.remove('hidden');
    renderBioCellulaQuestion();
}

function renderBioCellulaQuestion() {
    const quiz = bioCellulaEucariotaQuiz;
    const question = quiz.activeQuestions[quiz.currentQuestion];
    if (!question) return finishBioCellulaQuiz();

    document.getElementById('bio-cellula-eucariota-progress').textContent =
        `Pregunta ${quiz.currentQuestion + 1} de ${quiz.activeQuestions.length}`;
    document.getElementById('bio-cellula-eucariota-score').textContent = `Punts: ${quiz.score}`;
    document.getElementById('bio-cellula-eucariota-question').textContent = question.q;

    const options = document.getElementById('bio-cellula-eucariota-options');
    options.innerHTML = '';
    question.alternatives.forEach(answer => {
        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'btn quiz-option-button text-left';
        button.textContent = answer;
        button.addEventListener('click', () => answerBioCellulaQuestion(button, answer));
        options.appendChild(button);
    });

    const feedback = document.getElementById('bio-cellula-eucariota-feedback');
    feedback.textContent = '';
    setElementStateColor(feedback, 'muted');
    document.getElementById('bio-cellula-eucariota-explanation').textContent = '';
    document.getElementById('bio-cellula-eucariota-explanation').classList.add('hidden');
    const nextButton = document.getElementById('bio-cellula-eucariota-next');
    nextButton.textContent = quiz.currentQuestion === quiz.activeQuestions.length - 1
        ? 'Veure resultat'
        : 'Següent pregunta';
    nextButton.classList.add('hidden');
    nextButton.onclick = nextBioCellulaQuestion;
    quiz.locked = false;
}

function answerBioCellulaQuestion(selectedButton, answer) {
    const quiz = bioCellulaEucariotaQuiz;
    if (quiz.locked || quiz.finished) return;
    quiz.locked = true;

    const question = quiz.activeQuestions[quiz.currentQuestion];
    const isCorrect = answer === question.correct;
    const buttons = document.querySelectorAll('#bio-cellula-eucariota-options button');
    buttons.forEach(button => {
        button.disabled = true;
    });
    selectedButton.classList.add(isCorrect
        ? 'bio-cellula-eucariota__option--correct'
        : 'bio-cellula-eucariota__option--incorrect');

    const feedback = document.getElementById('bio-cellula-eucariota-feedback');
    if (isCorrect) {
        quiz.score += 10;
        feedback.textContent = 'Correcte!';
        setElementStateColor(feedback, 'success');
    } else {
        feedback.textContent = 'Incorrecte. Llegeix l’explicació i torna a pensar en el model.';
        setElementStateColor(feedback, 'error');
    }
    const explanation = document.getElementById('bio-cellula-eucariota-explanation');
    explanation.textContent = question.explanation;
    explanation.classList.remove('hidden');
    document.getElementById('bio-cellula-eucariota-next').classList.remove('hidden');
    document.getElementById('bio-cellula-eucariota-score').textContent = `Punts: ${quiz.score}`;
}

function nextBioCellulaQuestion() {
    const quiz = bioCellulaEucariotaQuiz;
    if (!quiz.locked || quiz.finished) return;

    quiz.currentQuestion++;
    if (quiz.currentQuestion >= quiz.activeQuestions.length) {
        finishBioCellulaQuiz();
    } else {
        renderBioCellulaQuestion();
    }
}

async function finishBioCellulaQuiz() {
    const quiz = bioCellulaEucariotaQuiz;
    if (quiz.finished) return;
    quiz.finished = true;

    const percentage = Math.round((quiz.score / (quiz.activeQuestions.length * 10)) * 100);
    document.getElementById('bio-cellula-eucariota-ui').classList.add('hidden');
    document.getElementById('bio-cellula-eucariota-results').classList.remove('hidden');
    document.getElementById('bio-cellula-eucariota-final-score').textContent = `${percentage}%`;

    const message = percentage >= 90
        ? 'Excel·lent! Domines el model de la cèl·lula.'
        : percentage >= 70
            ? 'Molt bé! Encara pots consolidar algun concepte.'
            : 'Convé repassar les parts i les funcions de les cèl·lules.';
    document.getElementById('bio-cellula-eucariota-message').textContent = message;

    if (typeof state !== 'undefined' && state.user && typeof callApi === 'function') {
        await callApi('saveResult', {
            email: state.user.email,
            curs: state.user.curs,
            projecte: state.currentProject ? state.currentProject.titol : 'Biologia',
            app: 'La cèl·lula eucariota',
            nivell: quiz.filterLabel,
            puntuacio: percentage,
            temps_segons: 0,
            feedback_pos: message,
            feedback_neg: ''
        });
    }
}
